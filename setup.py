#!/usr/bin/env python3
"""
setup.py - guided setup for installing Caelestia on Fedora Atomic.

The flow is split across two machines, so this script is phase-based and
resumable. It remembers where you got to in setup-state.json.

PHASE 1  prepare   (on the BUILD machine)
   Ask where the image should live, publish the builder image to that
   registry, regenerate the Containerfile against the published ref, write the
   BlueBuild CI workflow, and commit everything.

PHASE 2  push      (on the BUILD machine)
   Push to GitHub and tell you to enable BlueBuild on the repo.

PHASE 3  wait      (either machine)
   Poll the registry until the CI image appears, then report its digest and
   whether it is signed.

PHASE 4  rebase    (on the TARGET machine, Fedora Silverblue)
   Rebase to the unsigned image (this installs the signing policy), reboot.

PHASE 5  signed    (on the TARGET machine, after the reboot)
   Rebase to the signed image, apply NVIDIA kargs, reboot.

Usage
-----
    ./setup.py                 # interactive: figures out where you are and
                               #   walks you through the next step
    ./setup.py phase1          # jump straight to a phase
    ./setup.py status
    ./setup.py reset
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STATE = ROOT / "setup-state.json"
BUILD_PY = ROOT / "build.py"

_TTY = sys.stdout.isatty()


def c(code, s):
    return f"\033[{code}m{s}\033[0m" if _TTY else s


def info(m): print(c("36", "  " + m))
def ok(m):   print(c("32", "  ✓ " + m))
def warn(m): print(c("33", "  ! " + m))
def err(m):  print(c("31", "  ✗ " + m))
def step(m):
    print()
    print(c("1;36", f"━━ {m} ") + c("36", "━" * max(4, 60 - len(m))))


def die(m, code=1):
    err(m)
    sys.exit(code)


def ask(prompt, default=None, validate=None):
    while True:
        suffix = f" [{default}]" if default else ""
        try:
            ans = input(c("1;36", "? ") + prompt + suffix + ": ").strip()
        except EOFError:
            ans = ""
        if not ans and default:
            ans = default
        if not ans:
            warn("a value is required")
            continue
        if validate and not validate(ans):
            continue
        return ans


def ask_yn(prompt, default=True):
    d = "Y/n" if default else "y/N"
    try:
        ans = input(c("1;36", "? ") + f"{prompt} ({d}): ").strip().lower()
    except EOFError:
        ans = ""
    if not ans:
        return default
    return ans in ("y", "yes")


def load_state():
    return json.loads(STATE.read_text()) if STATE.exists() else {}


def save_state(s):
    STATE.write_text(json.dumps(s, indent=2) + "\n")


def sh(cmd, check=True, capture=False):
    r = subprocess.run(cmd, text=True,
                       stdout=subprocess.PIPE if capture else None,
                       stderr=subprocess.STDOUT if capture else None)
    if check and r.returncode != 0:
        if capture and r.stdout:
            print(r.stdout[-3000:])
        die(f"command failed: {' '.join(cmd)}")
    return r


def run_build(*args):
    sh([sys.executable, str(BUILD_PY), *args])


def build_py(*args):
    return subprocess.run([sys.executable, str(BUILD_PY), *args], text=True)


# ============================================================ detection =====


def is_ostree_system() -> bool:
    """True when running on an ostree/bootc deployment (i.e. Silverblue)."""
    return Path("/ostree/repo").exists() or Path("/run/ostree-booted").exists()


def have_git_remote() -> str | None:
    if not (ROOT / ".git").exists():
        return None
    r = subprocess.run(["git", "remote", "get-url", "origin"],
                       cwd=ROOT, text=True, capture_output=True)
    return r.stdout.strip() or None


def gh_user_from_remote(url: str | None) -> str | None:
    if not url:
        return None
    parts = url.rstrip("/").removesuffix(".git").split("/")
    if len(parts) >= 2 and parts[-2] not in ("", "."):
        return parts[-2]
    return None


# =============================================================== phase 1 ====

BLUEBUILD_WORKFLOW = """\
# Generated by setup.py - builds the image with BlueBuild.
name: Build

# NOTE: quoted deliberately. An unquoted bare `on:` is parsed by YAML 1.1 as
# the boolean True, which silently renames the trigger key and breaks the
# workflow on GitHub.
"on":
  push:
    branches: [main, live]
    tags: ['v*']
  workflow_dispatch:

jobs:
  build:
    name: Build and push the Caelestia Atomic image
    runs-on: ubuntu-latest
    permissions:
      contents: read
      packages: write
      id-token: write
    env:
      IMAGE_NAME: caelestia-fedora

    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Log in to ghcr.io
        uses: docker/login-action@v3
        with:
          registry: ghcr.io
          username: __GITHUB_ACTOR__
          password: __GITHUB_TOKEN__

      - name: Build the image with BlueBuild
        # NOTE: the action is blue-build/github-action. The old
        # `bluebuild/bluebuild-action` does not exist (404), so the workflow
        # died at this step. IMAGE_NAME was also not an input of the action;
        # the target registry is derived from `registry_token`.
        uses: blue-build/github-action@v1
        with:
          recipe: recipe.yml
          registry_token: __GITHUB_TOKEN__
          pr_event_number: ${{ github.event.number }}
          # REQUIRED input: the action aborts in seconds if it is absent.
          # Value is the cosign private key (repo secret SIGNING_SECRET);
          # cosign.pub is committed at the repo root for verification.
          cosign_private_key: ${{ secrets.SIGNING_SECRET }}
          # Same inputs wayblue uses. squash matters: without it no new
          # ostree commit is produced and rpm-ostree rebase is a no-op.
          squash: true
          build_chunked_oci: true
          max_layers: 128
          maximize_build_space: true
          retry_push_count: 3
          use_cache: false
          cli_version: v0.9.37
"""

BLUEPRINT = """\
# Minimal blueprint: the image is defined by the Containerfile at the repo
# root, which build.py generates and we have already validated locally.
blueprint:
  name: caelestia-fedora
  description: Caelestia shell + CLI on wayblue hyprland-nvidia-open
  packages:
    - git
    - jq
"""


def phase1(args):
    step("Phase 1 — prepare the build repository")
    s = load_state()

    remote = have_git_remote()
    user = gh_user_from_remote(remote)
    info(f"existing git remote: {remote or '(none)'}")

    gh = ask("GitHub owner (user or org)",
             s.get("gh_owner") or user,
             validate=lambda v: "/" not in v)
    repo = ask("GitHub repository name",
               s.get("repo") or "caelestia-fedora",
               validate=lambda v: v.replace("-", "").replace("_", "").isalnum())
    registry = ask("Container registry host", s.get("registry_host") or "ghcr.io")

    image = f"{registry}/{gh}/{repo}"
    builder = f"{registry}/{gh}/caelestia-builder"
    ok(f"image    -> {image}")
    ok(f"builder  -> {builder}")

    # Writing the CI files and the state does NOT depend on the upload, so do
    # that first: if the push fails (no login, no quota) the user still ends up
    # with a correct repo they can retry from, rather than nothing at all.
    step("Writing the BlueBuild CI files")
    wf = ROOT / ".github" / "workflows" / "build.yml"
    wf.parent.mkdir(parents=True, exist_ok=True)
    # Substitute the GitHub expressions at write time. They are plain `${{ }}`
    # in a normal Python string - no brace-doubling required, and doubling
    # would emit literal `${{{{ ... }}}}` into the workflow and break it.
    wf.write_text(
        BLUEBUILD_WORKFLOW
        .replace("__GITHUB_ACTOR__", "${{ github.actor }}")
        .replace("__GITHUB_TOKEN__", "${{ secrets.GITHUB_TOKEN }}")
        .replace("__REPO__", f"{gh}/{repo}")
    )
    ok(f"wrote {wf.relative_to(ROOT)}")
    (ROOT / "blueprint.yml").write_text(BLUEPRINT)
    ok("wrote blueprint.yml")

    s.update({
        "gh_owner": gh, "repo": repo, "registry_host": registry,
        "image": image, "builder": builder,
        "unsig_ref": f"ostree-unverified-registry:{image}:latest",
        "sig_ref": f"ostree-image-signed:docker://{image}:latest",
        "phase": 1,
    })
    save_state(s)
    ok("saved setup-state.json")

    step("Publishing the builder image")
    published = False
    if ask_yn(f"Push the builder image to {builder} now? (needs `podman login {registry}`)", True):
        info("this uploads the whole build toolchain and can take a while")
        r = build_py("publish-builder", "--registry", builder, "--tag", "f44")
        published = r.returncode == 0
        if published:
            ok("builder published, Containerfile regenerated against the registry ref")
        else:
            warn("builder publish FAILED - the CI build cannot work until this succeeds")
    else:
        warn("declined for now - you will need to run this before the CI can build:")
        warn(f"  ./build.py publish-builder --registry {builder} --tag f44")
    if not published:
        warn("The Containerfile still references a LOCAL builder image, so CI would")
        warn("fail until the builder is pushed. Everything else is configured.")

    step("Committing")
    if ask_yn("Create a git commit now?", True):
        sh(["git", "init"], check=False)
        sh(["git", "add", "-A"])
        r = subprocess.run(["git", "commit", "-m",
                            "Caelestia Fedora Atomic image + BlueBuild CI"],
                           cwd=ROOT, text=True, capture_output=True)
        ok("committed" if r.returncode == 0 else
           f"nothing to commit / skipped ({r.stdout.strip().splitlines()[-1] if r.stdout.strip() else ''})")

    step("Next: push and enable BlueBuild")
    print(f"""
  1. Create the repo on GitHub if you have not:
       https://github.com/new  ->  name it '{repo}'
  2. Push this directory:
       git remote add origin https://github.com/{gh}/{repo}.git
       git push -u origin HEAD
  3. Enable BlueBuild on the repo:
       https://github.com/{gh}/{repo}/settings/apps
     (BlueBuild then builds on every push and signs the image.)
  4. When the workflow goes green, come back and run:
       ./setup.py wait
""")
    s["phase"] = 1.5
    save_state(s)
    return 0


# =============================================================== phase 2 ====


def phase2(args):
    step("Phase 2 — push to GitHub")
    s = load_state()
    if not s.get("gh_owner"):
        die("run ./setup.py phase1 first")

    url = f"https://github.com/{s['gh_owner']}/{s['repo']}.git"
    if have_git_remote() is None:
        sh(["git", "remote", "add", "origin", url])
        ok(f"added origin {url}")
    sh(["git", "push", "-u", "origin", "HEAD"])
    ok("pushed")

    print(f"""
  Now enable BlueBuild:
    https://github.com/{s['gh_owner']}/{s['repo']}/settings/apps
  Then run:
    ./setup.py wait
""")
    s["phase"] = 2
    save_state(s)
    return 0


# =============================================================== phase 3 ====


def registry_token(registry: str, repo: str) -> str | None:
    """Anonymous pull token for ghcr.io / quay.io style registries."""
    if registry == "ghcr.io":
        url = (f"https://ghcr.io/token?scope=repository:{repo}:pull"
               "&service=ghcr.io")
    elif "quay.io" in registry:
        return None
    else:
        return None
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "caelestia-setup"})
        with urllib.request.urlopen(req, timeout=20) as r:
            return json.loads(r.read())["token"]
    except Exception:
        return None


# BlueBuild images are cosign-signed and the signature is published by
# cosign's legacy "tag-per-digest" convention, NOT via the OCI referrers API:
#   <sha256-hex-with-dash>.sig
# The Accept header must list the index media types too, because `latest`
# resolves to an OCI index - asking only for a plain manifest yields a 404.
_ACCEPT = ",".join([
    "application/vnd.oci.image.index.v1+json",
    "application/vnd.oci.image.manifest.v1+json",
    "application/vnd.docker.distribution.manifest.list.v2+json",
    "application/vnd.docker.distribution.manifest.v2+json",
])


def fetch_manifest_digest(registry: str, repo: str, tag: str):
    """Return (digest, signed) for a tag, or (None, None) if it is absent."""
    tok = registry_token(registry, repo)
    hdr = {"User-Agent": "caelestia-setup", "Accept": _ACCEPT}
    if tok:
        hdr["Authorization"] = f"Bearer {tok}"
    try:
        req = urllib.request.Request(
            f"https://{registry}/v2/{repo}/manifests/{tag}", headers=hdr)
        with urllib.request.urlopen(req, timeout=20) as r:
            digest = r.headers.get("Docker-Content-Digest")
    except Exception:
        return None, None
    if not digest:
        return None, None

    signed = False
    if digest.startswith("sha256:"):
        sig_tag = digest.replace(":", "-") + ".sig"
        try:
            req = urllib.request.Request(
                f"https://{registry}/v2/{repo}/manifests/{sig_tag}", headers=hdr)
            urllib.request.urlopen(req, timeout=20)
            signed = True
        except Exception:
            signed = False
    return digest, signed


def phase3(args):
    step("Phase 3 — wait for the CI image")
    s = load_state()
    if not s.get("image"):
        die("run ./setup.py phase1 first")
    image = s["image"]
    registry, repo = image.split("/", 1)
    repo = repo.rsplit(":", 1)[0]

    info(f"watching {image}")
    deadline = time.time() + args.timeout
    seen_digest = None
    while True:
        digest, signed = fetch_manifest_digest(registry, repo, "latest")
        if digest and digest != seen_digest:
            seen_digest = digest
            print()
            ok(f"image is available: {image}")
            info(f"digest: {digest}")
            if signed:
                ok("cosign signature found (sha256-<digest>.sig)")
            else:
                warn("no cosign signature yet - BlueBuild signs at the end of the build")
            print()
        if digest and signed:
            break
        if time.time() > deadline:
            err(f"timed out after {args.timeout}s waiting for a signed image")
            info("check the GitHub Actions run; then re-run ./setup.py wait")
            s["phase"] = 3
            save_state(s)
            return 2
        time.sleep(args.poll)
        sys.stdout.write(".")
        sys.stdout.flush()
    print()
    s["phase"] = 4
    s["digest"] = digest
    save_state(s)
    print(f"""
  The image is ready.

  Next, on your TARGET machine (the one running Silverblue):
      ./setup.py phase4
""")
    return 0


# =============================================================== phase 4 ====


def phase4(args):
    step("Phase 4 — rebase to the unsigned image")
    s = load_state()
    if not s.get("image"):
        die("run ./setup.py phase1 first")
    if not is_ostree_system():
        err("this does not look like an ostree/bootc system")
        err("run this on the machine that has Fedora Silverblue installed")
        return 1
    ok("ostree system detected")

    ref = s["unsig_ref"]
    info(f"rebase -> {ref}")
    warn("the unsigned rebase exists to install the ostree signing policy;")
    warn("it is required before the signed rebase will work.")
    if not ask_yn("Run the rebase now?", True):
        return 0
    sh(["rpm-ostree", "rebase", ref])
    ok("rebase staged")
    print()
    print(f"""
  Reboot now, then run:
      ./setup.py phase5
""")
    s["phase"] = 5
    save_state(s)
    return 0


# =============================================================== phase 5 ====


def phase5(args):
    step("Phase 5 — rebase to the signed image")
    s = load_state()
    if not s.get("image"):
        die("run ./setup.py phase1 first")
    if not is_ostree_system():
        err("this does not look like an ostree/bootc system")
        return 1

    ref = s["sig_ref"]
    info(f"rebase -> {ref}")
    if not ask_yn("Run the signed rebase now?", True):
        return 0
    sh(["rpm-ostree", "rebase", ref])
    ok("rebase staged")

    step("NVIDIA kernel arguments")
    if ask_yn("Apply the nvidia-open kargs now?", True):
        for kv in ("rd.driver.blacklist=nouveau",
                   "modprobe.blacklist=nouveau",
                   "nvidia-drm.modeset=1",
                   "nvidia-drm.fbdev=1"):
            sh(["rpm-ostree", "kargs", f"--append-if-missing={kv}"], check=False)
        ok("kargs applied")
    else:
        info(f"apply later with:")
        info("rpm-ostree kargs --append-if-missing=rd.driver.blacklist=nouveau \\")
        info("                 --append-if-missing=modprobe.blacklist=nouveau \\")
        info("                 --append-if-missing=nvidia-drm.modeset=1 \\")
        info("                 --append-if-missing=nvidia-drm.fbdev=1")

    print(f"""
  Reboot, then check:
      systemctl status caelestia-firstboot
      id neo
      hyprctl version

  You should land in the Caelestia desktop.
""")
    s["phase"] = 6
    save_state(s)
    return 0


# =============================================================== status ======


def cmd_status(args):
    s = load_state()
    step("Setup status")
    if not s:
        warn("no setup-state.json - nothing configured yet")
        info("start with: ./setup.py phase1")
        return 0
    order = ["not started", "prepared", "pushed", "image available",
             "unsigned rebase staged", "signed rebase staged", "complete"]
    p = s.get("phase", 0)
    ok(f"phase {p}: {order[p] if isinstance(p, int) and 0 <= p < len(order) else p}")
    for k in ("image", "builder", "digest"):
        if s.get(k):
            info(f"{k:9s} {s[k]}")
    print()
    nxt = {
        0: "./setup.py phase1", 1: "./setup.py phase1", 1.5: "./setup.py phase2",
        2: "./setup.py wait", 3: "./setup.py wait", 4: "./setup.py phase4",
        5: "./setup.py phase5",
    }
    info(f"next: {nxt.get(p, './setup.py wait')}")
    return 0


def cmd_resume(args):
    """Figure out where the user is and do the next thing."""
    s = load_state()
    p = s.get("phase", 0)
    if not s:
        return phase1(args)
    machine = "target (Silverblue)" if is_ostree_system() else "build"
    info(f"state: phase {p} | this machine looks like: {machine}")
    if p < 2:
        return phase1(args)
    if p < 3:
        return phase2(args)
    if p < 4:
        return phase3(args)
    if p < 5:
        return phase4(args)
    if p < 6:
        return phase5(args)
    ok("setup looks complete")
    cmd_status(args)
    return 0


def main():
    p = argparse.ArgumentParser(
        prog="setup.py", description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd")

    sub.add_parser("status", help="show where setup got to")
    sub.add_parser("reset", help="forget the saved state")
    sub.add_parser("phase1", help="prepare the build repository")
    sub.add_parser("phase2", help="push to GitHub")
    w = sub.add_parser("phase3", aliases=["wait"], help="wait for the CI image")
    w.add_argument("--timeout", type=int, default=1800)
    w.add_argument("--poll", type=int, default=20)
    sub.add_parser("phase4", help="rebase to the unsigned image (target machine)")
    sub.add_parser("phase5", help="rebase to the signed image (target machine)")
    sub.add_parser("run", help="resume automatically")

    args = p.parse_args()
    cmd = args.cmd
    if cmd is None:
        return cmd_resume(args)
    if cmd == "status":
        return cmd_status(args)
    if cmd == "reset":
        if STATE.exists():
            STATE.unlink()
            ok("state cleared")
        return 0
    if cmd in ("phase3", "wait"):
        return phase3(args)
    return {"run": cmd_resume, "phase1": phase1, "phase2": phase2,
            "phase4": phase4, "phase5": phase5}[cmd](args)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        err("interrupted")
        sys.exit(130)